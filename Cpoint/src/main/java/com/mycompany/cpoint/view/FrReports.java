    private void loadReport() {
        lblMonth.setText(selectedMonth.format(MONTH_FORMAT));

        DefaultTableModel model = (DefaultTableModel) tblHours.getModel();
        model.setRowCount(0);

        List<HoursSummary> report;
        try {
            report = reportController.buildMonthlyHoursReport(selectedMonth);
        } catch (DatabaseException ex) {
            JOptionPane.showMessageDialog(this, "Error loading the report: " + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        for (int i = 0; i < report.size(); i++) {
            HoursSummary summary = report.get(i);
            User user = summary.getUser();
            model.addRow(new Object[]{
                user.getFirstName() + " " + user.getLastName(),
                user.getDepartment(),
                user.getWeeklyHours() + "h",
                DurationFormat.formatHours(summary.getExpectedMinutes()),
                DurationFormat.formatHours(summary.getWorkedMinutes()),
                DurationFormat.formatBalance(summary.getBalanceMinutes())
            });
        }
    }

