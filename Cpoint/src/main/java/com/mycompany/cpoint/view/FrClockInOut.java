    private void showCurrentUser() {
        User user = UserSession.getCurrentUser();
        lblNameUser.setText(user.getFirstName() + " " + user.getLastName());
        lblDepartamentUser.setText(user.getDepartment());
    }

    private void startClock() {
        updateDateTime();

        clockTimer = new Timer(1000, new ActionListener() {
            @Override
            public void actionPerformed(ActionEvent evt) {
                updateDateTime();
            }
        });
        clockTimer.start();
    }

    private void updateDateTime() {
        LocalDateTime now = LocalDateTime.now();
        lblDate.setText(now.format(DAY_FORMAT));
        lblHour.setText(now.format(TIME_FORMAT));
    }

    @Override
    public void dispose() {
        if (clockTimer != null) {
            clockTimer.stop();
        }
        closeOpenScreens();
        super.dispose();
    }

    private boolean isClosed(JFrame screen) {
        if (screen == null) {
            return true;
        }
        return !screen.isDisplayable();
    }

    private void showScreen(JFrame screen) {
        screen.setVisible(true);
        screen.toFront();
    }

    private void closeOpenScreens() {
        JFrame[] screens = {viewTasksScreen, viewProjectsScreen, dailyPointScreen};

        for (int i = 0; i < screens.length; i++) {
            if (screens[i] != null) {
                screens[i].dispose();
            }
        }
    }

